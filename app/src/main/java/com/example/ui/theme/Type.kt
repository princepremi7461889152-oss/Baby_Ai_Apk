/**
 * Applies bundled Noto Sans Devanagari spans onto Devanagari Unicode runs (\u0900..\u097F)
 * while keeping Plus Jakarta Sans everywhere else for clean Hinglish + Hindi rendering.
 */
fun String.withDevanagariFallback(): AnnotatedString {
    if (none { it in '\u0900'..'\u097F' }) {
        return AnnotatedString(this)
    }
    return buildAnnotatedString {
        append(this@withDevanagariFallback)
        var i = 0
        while (i < length) {
            if (this@withDevanagariFallback[i] in '\u0900'..'\u097F') {
                val start = i
                while (i < length && (this@withDevanagariFallback[i] in '\u0900'..'\u097F' || this@withDevanagariFallback[i] == ' ')) {
                    i++
                }
                addStyle(
                    style = SpanStyle(fontFamily = NotoSansDevanagariFamily),
                    start = start,
                    end = i
                )
            } else {
                i++
            }
        }
    }
}

